let currentLang = 'en';

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('user_lang', lang);
  document.documentElement.lang = lang;

  // Translate static data-i18n elements
  const dict = TRANSLATIONS[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.innerHTML = dict[key];
      }
    }
  });

  // Translate static data-i18n-ph elements (placeholders)
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // Update active status on language selector UI if present
  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Dispatch global event for catalog re-render
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

export function initI18n() {
  const saved = localStorage.getItem('user_lang');
  const navLang = (navigator.language || 'en').slice(0, 2).toLowerCase();
  const initial = saved || (TRANSLATIONS[navLang] ? navLang : 'en');
  setLanguage(initial);
}
